// ─────────────────────────────────────────────────────────────────────────────
// Policy key catalogue — the SCHEMA of the Policy Registry.
//
// This file declares WHAT keys exist. The database holds WHAT they are currently
// set to. Same split as notifications/catalog.js, and for the same reason: the
// shape of the system is reviewable in a PR and deploys atomically with the code
// that consumes it, while the values stay operator-editable without a deploy.
//
// Three fields do the real work:
//
//   fallback           the value the code uses when the Registry is unseeded or
//                      unreachable. Seeded as v1, so adopting the Registry is a
//                      no-op replica of today's behaviour — NOT a silent mass
//                      application of the Terms & Conditions.
//
//   clause             the T&C clause that governs this key, or null when the key
//                      is purely operational and the contract says nothing.
//
//   clauseExpectation  what that clause states the value should be, when it states
//                      a number at all. `fallback !== clauseExpectation` IS the
//                      conflict — detected automatically, reported, and never
//                      auto-applied (see conflicts.js and docs/12).
//
// Values here are DATA. Nothing in this file is ever evaluated. The logic that
// uses a value stays in the module that owns it — refunds/policy.js still decides
// how a refund is banded; it just stops holding the numbers.
// ─────────────────────────────────────────────────────────────────────────────

