/** Fast lookup by key. */
export const KEYS_BY_ID = new Map(POLICY_KEYS.map((k) => [k.key, k]));

/** Every declared key id. */
export const ALL_KEYS = POLICY_KEYS.map((k) => k.key);

/** Definition for a key, or null. Never throws — callers decide how to degrade. */
export const getKeyDef = (key) => KEYS_BY_ID.get(key) || null;

/** Keys in a domain. */
export const keysInDomain = (domain) => POLICY_KEYS.filter((k) => k.domain === domain);

/** Keys frozen at a given snapshot boundary. */
export const keysInScope = (scope) => POLICY_KEYS.filter((k) => k.scope === scope);

/**
 * Keys an audience may read through the public bundle.
 * A consumer bundle must never contain commission rates — audience filtering is
 * server-side for exactly that reason.
 */
export const keysForAudience = (audience) => POLICY_KEYS.filter((k) => (k.audience || []).includes(audience));

/** Keys that require two approvers. */
export const moneyAffectingKeys = () => POLICY_KEYS.filter((k) => k.moneyAffecting === true);

/**
 * The fallback map — what the code uses when the Registry is unseeded or
 * unreachable. Seeded as v1 so adopting the Registry changes no behaviour.
 * A null fallback means "not implemented today", which is itself a conflict when
 * the governing clause states a value.
 */
export const fallbacks = () => Object.fromEntries(POLICY_KEYS.map((k) => [k.key, k.fallback]));
